import { z } from "astro:content";
import { authorSchema, contentReferenceSchema, linkedVideoSchema, photoSchema, practicalInformationSchema } from "../content/schema";
import { topicIds } from "./topics";
import { experienceCategoryIds } from "./experience-categories";

const locationLinkSchema = z.object({ label:z.string().min(1), href:z.string().startsWith("/").optional() });
const coordinatesSchema = z.object({
  latitude:z.number().min(-90).max(90),
  longitude:z.number().min(-180).max(180),
  system:z.enum(["WGS84", "GCJ-02", "BD-09"]),
});

export const placeSourceSchema = z.object({
  slug:z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  translationKey:z.string().min(1),
  title:z.string().min(1),
  englishName:z.string().min(1),
  chineseName:z.string().min(1).optional(),
  description:z.string().min(50).max(180),
  localSummary:z.string().min(1),
  whyItMatters:z.string().min(1).optional(),
  area:z.string().min(1).optional(),
  lang:z.enum(["en", "zh"]).default("en"),
  categories:z.array(z.enum(["river", "peak", "trail", "tea-area", "village", "neighborhood", "recreation-area"])).min(1),
  experienceCategories:z.array(z.enum(experienceCategoryIds)).default([]),
  mapExperienceFilters:z.array(z.enum(["family", "outdoor"])).default([]),
  localizations:z.object({
    chineseSummary:z.string().min(1).optional(),
    practicalInformation:z.object({ en:z.array(practicalInformationSchema).optional(), zh:z.array(practicalInformationSchema).optional() }).optional(),
  }).optional(),
  audience:z.array(z.string().min(1)).default([]),
  bestFor:z.array(z.string().min(1)).default([]),
  notSuitableFor:z.array(z.string().min(1)).optional(),
  bestSeason:z.string().min(1).optional(),
  suggestedTimeNeeded:z.string().min(1).optional(),
  walkingDifficulty:z.string().min(1).optional(),
  stairs:z.string().min(1).optional(),
  youngChildSuitability:z.string().min(1).optional(),
  strollerAccess:z.string().min(1).optional(),
  parking:z.string().min(1).optional(),
  restroom:z.string().min(1).optional(),
  publicTransportation:z.string().min(1).optional(),
  bestTimeOfDay:z.string().min(1).optional(),
  rainConsiderations:z.string().min(1).optional(),
  safetyNotes:z.string().min(1).optional(),
  lastPersonallyChecked:z.coerce.date().optional(),
  sourceStatus:z.enum(["personal-experience", "checked-on-location", "official-information", "reconfirm-before-travel"]),
  nearbyPlaces:z.array(locationLinkSchema).default([]),
  mapLink:z.string().url().optional(),
  relatedArticle:locationLinkSchema.optional(),
  videos:z.array(linkedVideoSchema).default([]),
  relatedTopics:z.array(z.enum(topicIds)).default([]),
  relatedRoutes:z.array(contentReferenceSchema).default([]),
  relatedStories:z.array(contentReferenceSchema).default([]),
  relatedRouteIds:z.array(z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/)).default([]),
  relatedStoryIds:z.array(z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/)).default([]),
  author:authorSchema.optional(),
  gallery:z.array(photoSchema).default([]),
  image:z.string().min(1).optional(),
  imageWebp:z.string().min(1).optional(),
  imageSrcset:z.string().min(1).optional(),
  imageAlt:z.string().optional(),
  imageWidth:z.number().int().positive().optional(),
  imageHeight:z.number().int().positive().optional(),
  imageNeedsReplacement:z.boolean().optional(),
  coordinates:coordinatesSchema.optional(),
  mapNote:z.string().min(1).optional(),
  schemaType:z.enum(["Place", "TouristAttraction"]).optional(),
  parentHref:z.string().startsWith("/").optional(),
  parentLabel:z.string().min(1).optional(),
  order:z.number().int().default(99),
  featured:z.boolean().default(false),
  recordStatus:z.enum(["draft", "published"]).default("draft"),
  published:z.coerce.date().optional(),
  updated:z.coerce.date().optional(),
});

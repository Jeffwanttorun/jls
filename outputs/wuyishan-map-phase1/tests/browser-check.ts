import 'dotenv/config';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir,writeFile } from 'node:fs/promises';
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'msedge',headless:true});
const base=process.env.TEST_BASE_URL||(process.env.DEV_HTTPS_CERT?'https://127.0.0.1:5173':'http://127.0.0.1:5173');
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
const checks:string[]=[];
await mkdir('reports/phase2/lan-no-auth/screenshots',{recursive:true});
try{
 await page.goto(base+'/map');
 await page.getByRole('heading',{name:'内部地图',exact:true}).waitFor();
 await page.getByText('GCJ-02 · 缩放',{exact:false}).waitFor();
 // Allow the external map tiles to render after the SDK has initialized.
 await page.waitForTimeout(5000);
 assert.equal(await page.getByRole('textbox',{name:'管理员令牌'}).count(),0);checks.push('电脑 HTTPS 直接进入真实地图，无令牌输入');
 await page.screenshot({path:'reports/phase2/lan-no-auth/screenshots/map-desktop-no-auth.png',fullPage:true});
 await page.goto(base+'/places');
 await page.getByText(/共 \d+ 个地点 · 读取已迁移数据/).waitFor();checks.push('直接访问当前地点列表');
 await page.screenshot({path:'reports/phase2/lan-no-auth/screenshots/places-desktop.png',fullPage:true});
 await page.getByLabel('搜索名称或业务编号').fill('WY-0024');
 await page.getByRole('button',{name:'查询',exact:true}).click();
 await page.getByText('共 1 个地点').waitFor();
 await page.getByRole('link',{name:'桃源峪',exact:true}).click();
 await page.getByRole('heading',{name:'桃源峪',exact:true}).waitFor();
 await page.getByRole('link',{name:'WY-0025 桃源峪停车位置'}).waitFor();
 await page.getByText('G-0001 桃源峪找蝴蝶',{exact:false}).waitFor();
 await page.getByText('R-0001 一号风景道·自然观察候选线',{exact:false}).waitFor();
 checks.push('详情父子、缺坐标、关联路线与攻略');
 await page.screenshot({path:'reports/phase2/lan-no-auth/screenshots/place-detail-desktop.png',fullPage:true});
 await page.getByRole('link',{name:'WY-0025 桃源峪停车位置'}).click();
 await page.getByRole('heading',{name:'桃源峪停车位置',exact:true}).waitFor();
 await page.getByRole('link',{name:'WY-0024 桃源峪'}).click();
 await page.getByRole('heading',{name:'桃源峪',exact:true}).waitFor();checks.push('父子页面往返');
 await page.getByRole('link',{name:'← 地点列表'}).click();
 await page.getByLabel('公开等级',{exact:true}).selectOption('P2');
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/admin/places?')&&r.status()===200),page.getByRole('button',{name:'查询',exact:true}).click()]);
 assert((await page.locator('tbody tr').count())>0);checks.push('公开等级筛选');
 await page.getByRole('button',{name:'重置',exact:true}).click();
 await page.getByText('共 46 个地点').waitFor();
 await page.getByRole('button',{name:'下一页'}).click();await page.getByText('第 2 / 2 页').waitFor();checks.push('分页');
 await page.setViewportSize({width:390,height:844});await page.goto(base+'/places/WY-0039');
 await page.getByRole('heading',{name:'红星村',exact:true}).waitFor();
 await page.screenshot({path:'reports/phase2/lan-no-auth/screenshots/place-detail-mobile.png',fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));checks.push('手机详情无横向溢出');
 assert.equal(await page.getByRole('textbox',{name:'管理员令牌'}).count(),0);checks.push('无令牌输入界面');
 assert.deepEqual(errors,[]);
 await writeFile('reports/phase2/lan-no-auth/desktop-browser.json',JSON.stringify({passed:true,checks,pageErrors:errors,checkedAt:new Date().toISOString()},null,2));
 console.log(JSON.stringify({passed:true,checks},null,2));
}finally{await browser.close();}
